    public static AppLocale Current { get; private set; } = AppLocale.En;

    public static event Action? Changed;

    public static void Set(AppLocale locale)
    {
        if (Current == locale) return;
        Current = locale;
        Changed?.Invoke();
    }

    public static void SetFromCode(string code) =>
        Set(code.ToLowerInvariant() switch
        {
            "sr" => AppLocale.Sr,
            "hu" => AppLocale.Hu,
            _ => AppLocale.En,
        });

    public static string Code =>
        Current switch
        {
            AppLocale.Sr => "sr",
            AppLocale.Hu => "hu",
            _ => "en",
        };

    public static string T(string key)
    {
        if (Tables[Current].TryGetValue(key, out var value)) return value;
        if (Tables[AppLocale.En].TryGetValue(key, out var fallback)) return fallback;
        return key;
    }

